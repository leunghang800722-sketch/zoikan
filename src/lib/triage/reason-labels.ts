/** 已知 code → 人話；動態前綴照前綴；真係未知先「其他原因」（唔露英文碼）。 */
export function reasonLabel(code: string): string {
  const exact = REASON_LABEL[code];
  if (exact) return exact;
  return PREFIX_LABEL.find(([p]) => code.startsWith(p))?.[1] ?? "其他原因";
}
