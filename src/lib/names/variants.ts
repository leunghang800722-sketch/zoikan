// 異體字（日式／舊字形，真訊息見到「厚徳商場」）→ 通用字。姓名同盤名比對共用。
const VARIANT_PAIRS: ReadonlyArray<readonly [string, string]> = [["徳", "德"], ["眞", "真"], ["靑", "青"], ["敎", "教"], ["髙", "高"], ["栁", "柳"], ["嶋", "島"], ["邉", "邊"], ["﨑", "崎"], ["凉", "涼"], ["峯", "峰"], ["吿", "告"]];
const MAP = new Map<string, string>([...PAIRS, ...VARIANT_PAIRS].filter(([a, b]) => a !== b).map(([a, b]) => [a, b]));

/** 只做字形折疊（NFKC＋簡→繁＋異體字），唔去空白標點、唔轉大小寫——盤名／別名比對用（兩邊都先折疊再比）。 */
export function foldVariants(s: string | null | undefined): string {
  if (!s) return "";
  let out = "";
  for (const ch of s.normalize("NFKC")) out += MAP.get(ch) ?? ch;
  return out;
}

/** NFKC、去空白／標點、簡→繁。純比對用，唔係顯示用。 */
export function normNameVariant(s: string | null | undefined): string {
  if (!s) return "";
  const t = s.normalize("NFKC").replace(/[\s()（）·．.,，、\-*]/g, "");
  let out = "";
  for (const ch of t) out += MAP.get(ch) ?? ch;
  return out;
}
